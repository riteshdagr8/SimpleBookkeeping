/**
 * Remove Payroll Remittance schedule rows.
 *
 * Payroll remittances are no longer generated; only Payroll Processing stays on
 * the schedule. This deletes the PayrollRemittance rows that were already
 * generated, so an existing database matches the new schedule.
 *
 *   npx tsx scripts/remove-payroll-remittance.ts                          # dry run
 *   npx tsx scripts/remove-payroll-remittance.ts --apply                  # delete rows with no recorded work
 *   npx tsx scripts/remove-payroll-remittance.ts --apply --include-worked # also delete rows with recorded work
 *
 * A row counts as having recorded work if any of these is true:
 *   - status is not Pending, or the row was entered by hand
 *   - it has a filed date, amount, confirmation number, or notes
 *   - its payroll workflow record has ticked checklist items or entered values
 *   - a client interaction ("waiting on client") is attached
 *
 * Rows with recorded work are skipped and listed unless --include-worked is
 * given. With that flag they are deleted too, together with their workflow
 * record and interactions.
 *
 * A snapshot of the database is written to backups/pre-migration before any
 * delete, and the script refuses to write if the snapshot fails. Stop the app
 * before running with --apply, as with the other maintenance scripts.
 * Idempotent: re-running after a successful apply finds nothing to do.
 */

import "dotenv/config";
import { createBackupSnapshot } from "./lib/backup-snapshot";
import { prisma } from "../src/lib/prisma";

const APPLY = process.argv.includes("--apply");
const INCLUDE_WORKED = process.argv.includes("--include-worked");
const FILING_TYPE = "PayrollRemittance";

const iso = (d: Date | null) => (d ? d.toISOString().slice(0, 10) : "—");

interface Candidate {
  id: string;
  clientId: string;
  periodStart: Date | null;
  periodEnd: Date | null;
  filingDueDate: Date | null;
  status: string;
  autoGenerated: boolean;
  dateFiled: Date | null;
  amount: number | null;
  confirmationNumber: string | null;
  notes: string | null;
}

/** Reasons this row has recorded work. Empty means it is safe to delete. */
async function workReasons(row: Candidate): Promise<string[]> {
  const reasons: string[] = [];
  if (row.status !== "Pending") reasons.push(`status ${row.status}`);
  if (!row.autoGenerated) reasons.push("entered by hand");
  if (row.dateFiled) reasons.push("filed date");
  if (row.amount != null) reasons.push("amount");
  if (row.confirmationNumber) reasons.push("confirmation number");
  if (row.notes) reasons.push("notes");

  const wf = await prisma.payrollProcessing.findUnique({ where: { obligationId: row.id } });
  if (wf) {
    if (wf.status !== "Pending") reasons.push(`workflow ${wf.status}`);
    let checked = false;
    try {
      const parsed = JSON.parse(wf.checklist);
      checked = !!parsed && typeof parsed === "object" && Object.values(parsed).some(Boolean);
    } catch {
      checked = false;
    }
    if (checked) reasons.push("workflow checklist ticked");
    if (wf.employeeCount != null || wf.totalRemittance != null || wf.employees) {
      reasons.push("workflow values entered");
    }
  }

  const interactions = await prisma.clientInteraction.count({ where: { targetId: row.id } });
  if (interactions > 0) reasons.push(`${interactions} client interaction(s)`);
  return reasons;
}

async function main() {
  console.log("=== Remove Payroll Remittance schedule rows ===");
  console.log(APPLY ? "Mode: APPLY (writing)" : "Mode: DRY RUN — nothing written (re-run with --apply)");
  console.log(INCLUDE_WORKED ? "Rows with recorded work: WILL be deleted (--include-worked)\n" : "Rows with recorded work: skipped and listed\n");

  const rows = (await prisma.filingObligation.findMany({
    where: { filingType: FILING_TYPE },
    select: {
      id: true, clientId: true, periodStart: true, periodEnd: true, filingDueDate: true,
      status: true, autoGenerated: true, dateFiled: true, amount: true,
      confirmationNumber: true, notes: true,
    },
    orderBy: [{ filingDueDate: "asc" }],
  })) as Candidate[];

  if (rows.length === 0) {
    console.log("No Payroll Remittance rows found. Nothing to do.");
    return;
  }

  const clientNames = new Map(
    (await prisma.client.findMany({ select: { id: true, fileNumber: true, legalName: true } })).map((c) => [
      c.id,
      `${c.legalName}${c.fileNumber ? ` (f#${c.fileNumber})` : ""}`,
    ])
  );
  const describe = (r: Candidate) =>
    `${clientNames.get(r.clientId) ?? r.clientId} — period ${iso(r.periodStart)} → ${iso(r.periodEnd)}, due ${iso(r.filingDueDate)} [${r.status}] (id ${r.id.slice(-8)})`;

  const clean: Candidate[] = [];
  const worked: Array<{ row: Candidate; reasons: string[] }> = [];
  for (const r of rows) {
    const reasons = await workReasons(r);
    if (reasons.length === 0) clean.push(r);
    else worked.push({ row: r, reasons });
  }

  const toDelete = INCLUDE_WORKED ? rows : clean;

  console.log(`Found ${rows.length} Payroll Remittance row(s): ${clean.length} with no recorded work, ${worked.length} with recorded work.\n`);

  if (clean.length > 0) {
    console.log("No recorded work (will be deleted):");
    for (const r of clean) console.log(`  ${describe(r)}`);
  }
  if (worked.length > 0) {
    console.log(`\nRecorded work (${INCLUDE_WORKED ? "will be deleted" : "skipped"}):`);
    for (const { row, reasons } of worked) {
      console.log(`  ${describe(row)}\n      ${reasons.join(", ")}`);
    }
  }

  console.log(`\n=== SUMMARY ===\n  Rows ${APPLY ? "deleted" : "to delete"}: ${toDelete.length}`);
  if (toDelete.length === 0) {
    console.log("\nNothing to delete.");
    return;
  }
  if (!APPLY) {
    console.log("\nDry run — nothing was written. Re-run with --apply to delete the rows above.");
    return;
  }

  console.log("\nCreating a backup snapshot first...");
  const snapshot = await createBackupSnapshot(undefined, "pre-remove-payroll-remittance");
  console.log(`Backup snapshot: ${snapshot.dbOut}`);

  const ids = toDelete.map((r) => r.id);
  // Interactions have no foreign key to the obligation, so they are removed
  // explicitly. Deleting the obligation cascades to its workflow record.
  const [interactions, obligations] = await prisma.$transaction([
    prisma.clientInteraction.deleteMany({ where: { targetId: { in: ids } } }),
    prisma.filingObligation.deleteMany({ where: { id: { in: ids }, filingType: FILING_TYPE } }),
  ]);
  console.log(`\nDeleted ${obligations.count} Payroll Remittance row(s) and ${interactions.count} client interaction(s).`);
  if (worked.length > 0 && !INCLUDE_WORKED) {
    console.log(`${worked.length} row(s) with recorded work were kept (see the list above).`);
  }
}

main()
  .catch((e) => {
    console.error("\nRemoval failed:", e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
