/**
 * Collapse duplicate FilingObligation rows.
 *
 * The old schedule generator only ever added rows, so a client could end up with
 * two copies of the same obligation differing by a day or two in `periodStart`.
 * This finds those pairs and deletes the extra one.
 *
 *   npx tsx scripts/dedup-obligations.ts          # dry run — prints the plan
 *   npx tsx scripts/dedup-obligations.ts --apply  # writes (backup first)
 *
 * "Duplicate" means: same client, same filing type, same due date, and the
 * periods are near-identical — both endpoints within a day of each other. That
 * deliberately excludes rows that merely share a due date but cover genuinely
 * different periods (e.g. a quarterly and a monthly return landing on the same
 * deadline); those are left alone. The fuller period is kept.
 *
 * A group is skipped (never deleted) if any of its rows has a workflow row or a
 * client interaction attached. Idempotent — safe to re-run.
 */

import "dotenv/config";
import { createBackupSnapshot } from "./lib/backup-snapshot";
import { prisma } from "../src/lib/prisma";

const APPLY = process.argv.includes("--apply");
const DAY = 24 * 60 * 60 * 1000;
/** How far two rows' period endpoints may differ and still count as one obligation. */
const NEAR_MS = 2 * DAY;

const WORKFLOW_MODELS = [
  "payrollProcessing",
  "gSTHSTProcessing",
  "t2Processing",
  "ontarioARProcessing",
  "federalARProcessing",
  "infoReturnProcessing",
] as const;

interface Row {
  id: string;
  clientId: string;
  filingType: string;
  periodStart: Date | null;
  periodEnd: Date | null;
  filingDueDate: Date | null;
  status: string;
  autoGenerated: boolean;
}

const iso = (d: Date | null) => (d ? d.toISOString().slice(0, 10) : "—");
const span = (r: Row) =>
  r.periodStart && r.periodEnd ? r.periodEnd.getTime() - r.periodStart.getTime() : -1;

async function hasAttachments(id: string): Promise<string[]> {
  const hits: string[] = [];
  for (const m of WORKFLOW_MODELS) {
    const n = await (prisma[m] as unknown as { count: (a: { where: { obligationId: string } }) => Promise<number> })
      .count({ where: { obligationId: id } });
    if (n > 0) hits.push(m);
  }
  const ci = await prisma.clientInteraction.count({ where: { targetId: id } });
  if (ci > 0) hits.push(`ClientInteraction×${ci}`);
  return hits;
}

async function main() {
  console.log("=== De-duplicate FilingObligations ===");
  console.log(APPLY ? "Mode: APPLY (writing)\n" : "Mode: DRY RUN — nothing written (re-run with --apply)\n");

  const rows = (await prisma.filingObligation.findMany({
    where: { autoGenerated: true, status: "Pending" },
    select: {
      id: true, clientId: true, filingType: true, periodStart: true, periodEnd: true,
      filingDueDate: true, status: true, autoGenerated: true,
    },
  })) as Row[];

  // Group by client + filing type + due date.
  const groups = new Map<string, Row[]>();
  for (const r of rows) {
    const k = `${r.clientId}|${r.filingType}|${r.filingDueDate?.getTime() ?? 0}`;
    groups.set(k, [...(groups.get(k) ?? []), r]);
  }

  const clientNames = new Map(
    (await prisma.client.findMany({ select: { id: true, fileNumber: true, legalName: true } }))
      .map((c) => [c.id, `${c.legalName}${c.fileNumber ? ` (f#${c.fileNumber})` : ""}`])
  );

  const toDelete: Row[] = [];
  const skipped: string[] = [];

  for (const group of groups.values()) {
    if (group.length < 2) continue;

    // Near-identical periods only: both endpoints within NEAR_MS of each other.
    const starts = group.map((r) => r.periodStart?.getTime() ?? 0);
    const ends = group.map((r) => r.periodEnd?.getTime() ?? 0);
    const nearInTime = Math.max(...starts) - Math.min(...starts) <= NEAR_MS &&
      Math.max(...ends) - Math.min(...ends) <= NEAR_MS;
    if (!nearInTime) {
      skipped.push(`${clientNames.get(group[0].clientId)} ${group[0].filingType} due ${iso(group[0].filingDueDate)} — ${group.length} rows share a due date but cover different periods`);
      continue;
    }

    // Safety: never delete a row that carries workflow/interaction data.
    const attached: string[] = [];
    for (const r of group) {
      const hits = await hasAttachments(r.id);
      if (hits.length) attached.push(`${r.id.slice(-8)} → ${hits.join(", ")}`);
    }
    if (attached.length) {
      skipped.push(`${clientNames.get(group[0].clientId)} ${group[0].filingType} due ${iso(group[0].filingDueDate)} — has attached data: ${attached.join("; ")}`);
      continue;
    }

    // Keep the fuller period; delete the rest.
    const sorted = [...group].sort((a, b) => span(b) - span(a));
    const keep = sorted[0];
    const drop = sorted.slice(1);
    console.log(`  ${clientNames.get(group[0].clientId)} — ${group[0].filingType} due ${iso(group[0].filingDueDate)}`);
    console.log(`      KEEP   ${iso(keep.periodStart)} → ${iso(keep.periodEnd)}  (id ${keep.id.slice(-8)})`);
    for (const d of drop) {
      console.log(`      DELETE ${iso(d.periodStart)} → ${iso(d.periodEnd)}  (id ${d.id.slice(-8)})`);
      toDelete.push(d);
    }
  }

  if (skipped.length) {
    console.log("\n  Skipped (left untouched):");
    for (const s of skipped) console.log(`    ${s}`);
  }

  console.log("\n=== SUMMARY ===");
  console.log(`  Rows ${APPLY ? "deleted" : "to delete"} : ${toDelete.length}`);

  if (toDelete.length === 0) {
    console.log("\nNothing to do.");
    return;
  }
  if (!APPLY) {
    console.log("\nDry run — nothing was written. Re-run with --apply to delete the rows above.");
    return;
  }

  console.log("\nCreating a backup snapshot first...");
  const snapshot = await createBackupSnapshot(undefined, "pre-obligation-dedup");
  console.log(`Backup snapshot: ${snapshot.dbOut}`);

  await prisma.$transaction([
    prisma.filingObligation.deleteMany({ where: { id: { in: toDelete.map((r) => r.id) } } }),
  ]);
  console.log(`\nDeleted ${toDelete.length} duplicate obligation row(s).`);
  console.log("Run `npm run backfill-fye -- --apply --past-months=13` next so the surviving rows pick up the corrected dates.");
}

main()
  .catch((e) => {
    console.error("\nDe-dup failed:", e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
