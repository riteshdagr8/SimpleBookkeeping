export interface ObligationDates {
  periodStart: Date | null;
  periodEnd: Date | null;
  filingDueDate: Date | null;
  paymentDueDate: Date | null;
}

export interface ObligationDateChange {
  id: string;
  filingType: string;
  before: ObligationDates;
  after: ObligationDates;
}

export interface ReconcilePlan {
  changes: ObligationDateChange[];
  deletions: Array<{ id: string; filingType: string }>;
}

function sameTime(a: Date | null, b: Date | null): boolean {
  if (a === null || b === null) return a === b;
  return a.getTime() === b.getTime();
}

interface ExistingObligation {
  id: string;
  filingType: string;
  periodStart: Date | null;
  periodEnd: Date | null;
  filingDueDate: Date | null;
  paymentDueDate: Date | null;
}

/** Periods are "close" when both endpoints are within a few days of each other. */
const PERIOD_TOLERANCE_MS = 3 * 24 * 60 * 60 * 1000;

function periodsClose(a: ExistingObligation | ScheduleRow, b: ExistingObligation | ScheduleRow): boolean {
  const as = a.periodStart?.getTime();
  const bs = b.periodStart?.getTime();
  const ae = a.periodEnd?.getTime();
  const be = b.periodEnd?.getTime();
  if (as === undefined || bs === undefined || ae === undefined || be === undefined) return false;
  return Math.abs(as - bs) <= PERIOD_TOLERANCE_MS && Math.abs(ae - be) <= PERIOD_TOLERANCE_MS;
}

/**
 * Pair a stored obligation with the schedule row that should describe it.
 *
 * Exact period first, then a near-equal period (both endpoints within a few
 * days), then — only when the type has a single stored and a single desired row
 * — by type alone. That last fallback is what lets a row whose period was
 * written entirely wrong by an older rule still be corrected.
 *
 * The period must match on BOTH endpoints. Matching on the start alone would
 * pair a stale monthly row with a quarterly one that shares its start month,
 * rewriting the monthly row onto the quarterly period and manufacturing a
 * duplicate. The strictness of the earlier passes is also what keeps the pass
 * safe as the rolling window advances: a window-anchored row whose period has
 * moved on finds no partner and is left alone.
 */
function matchDesired(
  row: ExistingObligation,
  desired: ScheduleRow[],
  used: Set<ScheduleRow>,
  existing: ExistingObligation[]
): ScheduleRow | null {
  const free = desired.filter((d) => d.filingType === row.filingType && !used.has(d));
  const exact = free.find(
    (d) => sameTime(d.periodStart ?? null, row.periodStart) && sameTime(d.periodEnd ?? null, row.periodEnd)
  );
  if (exact) return exact;
  const near = free.find((d) => periodsClose(row, d));
  if (near) return near;

  // A row whose period ends before it starts was written by a broken rule and
  // can never be correct, so period-based matching can't reach it. Match it on
  // its start alone — safe here because a start is unique within a filing type
  // over the window, and because we only relax for a provably malformed period.
  const broken = !!row.periodStart && !!row.periodEnd && row.periodStart.getTime() > row.periodEnd.getTime();
  if (broken) {
    const sameStart = free.find((d) => sameTime(d.periodStart ?? null, row.periodStart));
    if (sameStart) return sameStart;
  }

  const ofType = desired.filter((d) => d.filingType === row.filingType);
  const existingOfType = existing.filter((e) => e.filingType === row.filingType);
  if (ofType.length === 1 && existingOfType.length === 1 && !used.has(ofType[0])) return ofType[0];
  return null;
}

/** A move of the fiscal year-end: dates derived from `from` become derived from `to`. */
export interface FyeShift {
  from: Date;
  to: Date;
}

/**
 * Re-derive a client's auto-generated, Pending, future obligations and report
 * how they would change — then, when `apply` is true, write the updates and
 * deletions in place. Rows keep their ids (and therefore their workflow rows
 * and interactions); only their dates move. Filed/Completed and past rows are
 * never touched, and rows whose filing type is no longer valid are deleted
 * (mirroring the generator's reconcile).
 *
 * Matching is strict (see matchDesired): a row is only rewritten when a desired
 * row covers the same period, so rows the old code wrote with a wrong period
 * are corrected while window-anchored rows whose period has rolled on are left
 * alone. A specific fiscal-year-end shift can be applied to the desired dates
 * via `shift`, so the result does not depend on whether the caller has already
 * written the client row.
 *
 * Unlike generateObligationsForClient this never creates rows — adding missing
 * obligations is the job of "Generate schedule".
 */
export async function reconcilePendingObligations(
  tenantId: string,
  actorId: string | null,
  clientId: string,
  apply: boolean,
  shift?: FyeShift,
  opts?: { pastMonths?: number }
): Promise<ReconcilePlan | null> {
  const client = await prisma.client.findFirst({ where: { id: clientId, tenantId } });
  if (!client) return null;

  const today = new Date();
  const windowStart = new Date(Date.UTC(today.getUTCFullYear(), today.getUTCMonth(), 1));
  const windowEnd = new Date(windowStart);
  windowEnd.setUTCMonth(windowEnd.getUTCMonth() + 12);

  // Desired rows, optionally as derived from a different year-end than the one
  // stored on the client (used by the FYE backfill before it has written the
  // new value).
  const effectiveFye = shift && shift.to.getTime() !== shift.from.getTime() ? shift.to : client.fiscalYearEnd;

  // The forward window covers the actionable (current + future) rows. A repair
  // pass can also add a window reaching back over already-past rows, so their
  // dates can be corrected too.
  const windows: Array<[Date, Date]> = [[windowStart, windowEnd]];
  if (opts?.pastMonths && opts.pastMonths > 0) {
    const pastStart = new Date(windowStart);
    pastStart.setUTCMonth(pastStart.getUTCMonth() - opts.pastMonths);
    windows.push([pastStart, windowStart]);
  }
  const desired: ScheduleRow[] = [];
  for (const [start, end] of windows) {
    desired.push(...buildScheduleRows({ ...client, fiscalYearEnd: effectiveFye }, start, end).rows);
  }

  const validTypes = filingTypesForClient(clientComplianceConfig(client));

  // With a past window in play, past-due rows become eligible for correction.
  const includePast = (opts?.pastMonths ?? 0) > 0;
  const existing = await prisma.filingObligation.findMany({
    where: {
      clientId,
      autoGenerated: true,
      status: "Pending",
      ...(includePast ? {} : { OR: [{ filingDueDate: null }, { filingDueDate: { gte: today } }] }),
    },
    select: { id: true, filingType: true, periodStart: true, periodEnd: true, filingDueDate: true, paymentDueDate: true },
  });

  const changes: ObligationDateChange[] = [];
  const deletions: Array<{ id: string; filingType: string }> = [];
  const used = new Set<ScheduleRow>();

  for (const row of existing) {
    if (!validTypes.has(row.filingType)) {
      deletions.push({ id: row.id, filingType: row.filingType });
      continue;
    }
    const best = matchDesired(row, desired, used, existing);
    if (!best) continue;
    used.add(best);

    const before: ObligationDates = {
      periodStart: row.periodStart,
      periodEnd: row.periodEnd,
      filingDueDate: row.filingDueDate,
      paymentDueDate: row.paymentDueDate,
    };
    const after: ObligationDates = {
      periodStart: best.periodStart ?? null,
      periodEnd: best.periodEnd ?? null,
      filingDueDate: best.filingDueDate ?? null,
      paymentDueDate: best.paymentDueDate ?? null,
    };
    if (
      sameTime(before.periodStart, after.periodStart) &&
      sameTime(before.periodEnd, after.periodEnd) &&
      sameTime(before.filingDueDate, after.filingDueDate) &&
      sameTime(before.paymentDueDate, after.paymentDueDate)
    ) {
      continue;
    }
    changes.push({ id: row.id, filingType: row.filingType, before, after });
  }

  if (apply && actorId && (changes.length > 0 || deletions.length > 0)) {
    await prisma.$transaction([
      ...changes.map((c) =>
        prisma.filingObligation.update({
          where: { id: c.id },
          data: {
            periodStart: c.after.periodStart,
            periodEnd: c.after.periodEnd,
            filingDueDate: c.after.filingDueDate,
            paymentDueDate: c.after.paymentDueDate,
          },
        })
      ),
      ...(deletions.length > 0
        ? [prisma.filingObligation.deleteMany({ where: { id: { in: deletions.map((d) => d.id) } } })]
        : []),
    ]);
    await writeAudit({
      tenantId,
      actorId,
      action: "SCHEDULE_RECONCILED",
      entity: "Client",
      entityId: clientId,
      metadata: { updated: changes.length, deleted: deletions.length },
    });
  }

  return { changes, deletions };
}

export async function updateObligation(
  tenantId: string,
  actorId: string,
  clientId: string,
  obligationId: string,
  input: ObligationUpdate
) {
  const client = await prisma.client.findFirst({ where: { id: clientId, tenantId } });
  if (!client) return null;
  const obligation = await prisma.filingObligation.findFirst({
    where: { id: obligationId, clientId },
  });
  if (!obligation) return null;
  // Caller (the API route) is expected to have already validated `input` with
  // updateSchema. We trust the typed shape here and skip a redundant parse.

  const data: Record<string, unknown> = {};
  if (input.status !== undefined) data.status = input.status;
  if (input.amount !== undefined) data.amount = input.amount;
  if (input.confirmationNumber !== undefined) data.confirmationNumber = input.confirmationNumber;
  if (input.notes !== undefined) data.notes = input.notes;
  if (input.dateFiled !== undefined) {
    data.dateFiled =
      input.dateFiled === null
        ? null
        : input.dateFiled instanceof Date
          ? input.dateFiled
          : new Date(input.dateFiled);
  }

  const updated = await prisma.filingObligation.update({ where: { id: obligationId }, data });
  await writeAudit({
    tenantId,
    actorId,
    action: "OBLIGATION_UPDATED",
    entity: "FilingObligation",
    entityId: obligationId,
    metadata: { changes: Object.keys(data) },
  });
  return updated;
}

