/**
 * Realign Weekly and Bi-Weekly Payroll Processing runs to the firm-wide cycle.
 *
 * Weekly runs end on a Friday. Bi-weekly runs end on a Friday, every 14 days from
 * PAYROLL_CYCLE_REFERENCE_END (see src/lib/compliance-rules.ts). Earlier versions
 * of the generator counted cycles from the first of the month the schedule was
 * generated, so one client could end up with several overlapping cycles.
 *
 *   npx tsx scripts/realign-payroll-cycles.ts          # dry run: prints the plan
 *   npx tsx scripts/realign-payroll-cycles.ts --apply  # writes (snapshot first)
 *
 * What it changes, and only this:
 *   - DELETES pending, future Payroll Processing runs that are on a cycle the
 *     firm no longer uses (off the fixed grid), or whose frequency the client no
 *     longer has selected.
 *   - ADDS the missing on-grid Weekly and Bi-Weekly runs for the 12-month window
 *     from the current month, for active clients with a completed review.
 *
 * What it never changes:
 *   - Any run with recorded work: a workflow record, a client interaction, a
 *     status other than Pending, a filed date, amount, confirmation number or
 *     notes, or a manually entered row. These are listed and kept.
 *   - Past-due runs (filing due before today). These are history.
 *   - Monthly and Semi-Monthly runs, and every other filing type.
 *
 * A snapshot of the database is written to backups/pre-migration before any
 * write, and the script stops if the snapshot fails. Stop the app first.
 * Idempotent: a second --apply finds nothing to do.
 */

import "dotenv/config";
import { basename } from "path";
import { createBackupSnapshot } from "./lib/backup-snapshot";
import { prisma } from "../src/lib/prisma";
import {
  PAYROLL_CYCLE_DAYS,
  PAYROLL_CYCLE_REFERENCE_END,
} from "../src/lib/compliance-rules";
import { buildScheduleRows } from "../src/lib/services/obligations";
import { writeAudit } from "../src/lib/services/audit";
import { frequencyForPeriod, parsePayFrequencies } from "../src/lib/payroll-frequency";

const APPLY = process.argv.includes("--apply");
const DAY = 24 * 60 * 60 * 1000;
const CYCLE = ["Weekly", "Bi-Weekly"] as const;
type CycleFreq = (typeof CYCLE)[number];

const iso = (d: Date | null) => (d ? d.toISOString().slice(0, 10) : "—");
const keyOf = (r: { periodStart: Date | null; periodEnd: Date | null; filingDueDate: Date | null; paymentDueDate: Date | null }) =>
  [r.periodStart, r.periodEnd, r.filingDueDate, r.paymentDueDate]
    .map((d) => (d ? d.getTime() : "-"))
    .join("|");

/** True when a period end lies on the firm-wide grid for this frequency. */
function onGrid(periodEnd: Date, freq: CycleFreq): boolean {
  const step = PAYROLL_CYCLE_DAYS[freq] * DAY;
  return (periodEnd.getTime() - PAYROLL_CYCLE_REFERENCE_END.getTime()) % step === 0;
}

async function main() {
  console.log("=== Realign Weekly / Bi-Weekly payroll runs ===");
  console.log(APPLY ? "Mode: APPLY (writing)\n" : "Mode: DRY RUN — nothing written (re-run with --apply)\n");
  console.log(`Firm-wide cycle: Weekly and Bi-Weekly end on Fridays; reference period end ${iso(PAYROLL_CYCLE_REFERENCE_END)}.\n`);

  const today = new Date(new Date().toISOString().slice(0, 10) + "T00:00:00Z");
  const windowStart = new Date(Date.UTC(today.getUTCFullYear(), today.getUTCMonth(), 1));
  const windowEnd = new Date(windowStart);
  windowEnd.setUTCMonth(windowEnd.getUTCMonth() + 12);

  const admin = await prisma.user.findFirst({ where: { role: "Admin" }, select: { id: true } });
  if (!admin) throw new Error("No Admin user exists; cannot record the audit entries.");

  const clients = await prisma.client.findMany({
    where: { obligations: { some: { filingType: "PayrollProcessing" } } },
    orderBy: { legalName: "asc" },
  });

  let totalDelete = 0, totalAdd = 0, totalKeptWork = 0, totalPast = 0;
  const plans: Array<{
    clientId: string;
    tenantId: string;
    toDelete: string[];
    toAdd: Array<ReturnType<typeof buildScheduleRows>["rows"][number]>;
  }> = [];

  for (const client of clients) {
    const selected = client.payrollApplicable ? parsePayFrequencies(client.payrollFrequency) : [];
    const runs = await prisma.filingObligation.findMany({
      where: { clientId: client.id, filingType: "PayrollProcessing" },
      select: {
        id: true, periodStart: true, periodEnd: true, filingDueDate: true, paymentDueDate: true,
        status: true, autoGenerated: true, dateFiled: true, amount: true,
        confirmationNumber: true, notes: true,
        payrollProcessing: { select: { id: true } },
      },
    });
    const interactionCounts = await prisma.clientInteraction.groupBy({
      by: ["targetId"],
      where: { targetType: "Payroll", targetId: { in: runs.map((r) => r.id) } },
      _count: { _all: true },
    });
    const withInteraction = new Set(interactionCounts.map((i) => i.targetId));

    const toDelete: string[] = [];
    const keptWork: string[] = [];
    let past = 0;
    for (const r of runs) {
      if (!r.periodStart || !r.periodEnd) continue;
      const freq = frequencyForPeriod(r.periodStart, r.periodEnd);
      if (!freq || !(CYCLE as readonly string[]).includes(freq)) continue;
      const cycleFreq = freq as CycleFreq;
      const offGrid = !onGrid(r.periodEnd, cycleFreq);
      const notSelected = !selected.includes(cycleFreq);
      if (!offGrid && !notSelected) continue;

      if (r.filingDueDate && r.filingDueDate.getTime() < today.getTime()) {
        past++;
        continue;
      }
      const hasWork =
        !!r.payrollProcessing ||
        withInteraction.has(r.id) ||
        r.status !== "Pending" ||
        !r.autoGenerated ||
        !!r.dateFiled ||
        r.amount != null ||
        !!r.confirmationNumber ||
        !!r.notes;
      if (hasWork) {
        keptWork.push(`${iso(r.periodStart)} → ${iso(r.periodEnd)} (${cycleFreq}${offGrid ? ", off-cycle" : ", frequency no longer selected"})`);
        continue;
      }
      toDelete.push(r.id);
    }

    // Missing on-grid runs for active, reviewed clients.
    const toAdd: ReturnType<typeof buildScheduleRows>["rows"] = [];
    if (client.active && client.reviewComplete && client.payrollApplicable && selected.some((f) => (CYCLE as readonly string[]).includes(f))) {
      const desired = buildScheduleRows(client, windowStart, windowEnd).rows.filter(
        (r) => r.filingType === "PayrollProcessing" && r.periodStart && r.periodEnd &&
          (CYCLE as readonly string[]).includes(frequencyForPeriod(r.periodStart, r.periodEnd) ?? "")
      );
      const deleting = new Set(toDelete);
      const existing = new Set(runs.filter((r) => !deleting.has(r.id)).map((r) => keyOf(r)));
      for (const d of desired) {
        if (!existing.has(keyOf({
          periodStart: d.periodStart ?? null, periodEnd: d.periodEnd ?? null,
          filingDueDate: d.filingDueDate ?? null, paymentDueDate: d.paymentDueDate ?? null,
        }))) toAdd.push(d);
      }
    }

    if (toDelete.length === 0 && toAdd.length === 0 && keptWork.length === 0 && past === 0) continue;

    totalDelete += toDelete.length;
    totalAdd += toAdd.length;
    totalKeptWork += keptWork.length;
    totalPast += past;
    if (toDelete.length || toAdd.length) plans.push({ clientId: client.id, tenantId: client.tenantId, toDelete, toAdd });

    const label = `${client.legalName}${client.fileNumber ? ` (f#${client.fileNumber})` : ""}`;
    console.log(`${label}  [selected: ${selected.join(", ") || "none"}${client.active ? "" : ", INACTIVE"}${client.reviewComplete ? "" : ", review not complete"}]`);
    console.log(`    remove ${toDelete.length} off-cycle pending run(s); add ${toAdd.length} on-cycle run(s); kept with work ${keptWork.length}; past-due untouched ${past}`);
    for (const k of keptWork) console.log(`      kept (work recorded): ${k}`);
  }

  console.log("\n=== SUMMARY ===");
  console.log(`  Runs ${APPLY ? "removed" : "to remove"}: ${totalDelete}`);
  console.log(`  Runs ${APPLY ? "added" : "to add"}: ${totalAdd}`);
  console.log(`  Kept because work is recorded: ${totalKeptWork}`);
  console.log(`  Past-due runs untouched: ${totalPast}`);

  if (plans.length === 0) {
    console.log("\nNothing to change.");
    return;
  }
  if (!APPLY) {
    console.log("\nDry run — nothing was written. Re-run with --apply to make these changes.");
    return;
  }

  console.log("\nCreating a backup snapshot first...");
  const snapshot = await createBackupSnapshot(undefined, "pre-realign-payroll-cycles");
  console.log(`Backup saved as: ${basename(snapshot.dbOut)}`);
  console.log(`Location       : ${snapshot.dbOut}`);

  const allDelete = plans.flatMap((p) => p.toDelete);
  const allAdd = plans.flatMap((p) =>
    p.toAdd.map((r) => ({
      clientId: p.clientId,
      filingType: "PayrollProcessing",
      periodStart: r.periodStart ?? null,
      periodEnd: r.periodEnd ?? null,
      filingDueDate: r.filingDueDate ?? null,
      paymentDueDate: r.paymentDueDate ?? null,
      status: "Pending",
    }))
  );

  await prisma.$transaction([
    ...(allDelete.length > 0
      ? [prisma.filingObligation.deleteMany({ where: { id: { in: allDelete }, filingType: "PayrollProcessing" } })]
      : []),
    ...(allAdd.length > 0 ? [prisma.filingObligation.createMany({ data: allAdd })] : []),
  ]);

  for (const p of plans) {
    await writeAudit({
      tenantId: p.tenantId,
      actorId: admin.id,
      action: "PAYROLL_CYCLE_REALIGNED",
      entity: "Client",
      entityId: p.clientId,
      metadata: { removed: p.toDelete.length, added: p.toAdd.length },
    });
  }

  console.log(`\nRemoved ${allDelete.length} off-cycle run(s) and added ${allAdd.length} on-cycle run(s).`);
  console.log(`Runs with recorded work and past-due runs were left as they were (${totalKeptWork} kept, ${totalPast} past-due).`);
}

main()
  .catch((e) => {
    console.error("\nRealignment failed:", e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
