/**
 * Obligations for a fiscal year, built for the historical review.
 *
 * When a review cell is Overdue or Outstanding Balance, the client should have
 * that group's filings for that year, with their real dates (four HST quarters,
 * 52 weekly payroll runs, and so on). When the cell is Filed or N/A, those
 * filings should not stay pending.
 *
 * "Year" means the fiscal year that ends in that calendar year: the period runs
 * from the day after the prior year-end through the year-end in `year`.
 *
 * Rows created from the review carry `reviewYear`, so they can be found and
 * cancelled later without touching rows the normal schedule created.
 */

import { prisma } from "@/lib/prisma";
import { writeAudit } from "@/lib/services/audit";
import { utc } from "@/lib/compliance-rules";
import { buildScheduleRows, type ScheduleClientInput } from "@/lib/services/obligations";
import type { ReviewGroup } from "@/lib/review-groups";

/** The fiscal-year window ending in calendar year `year`. */
export function fiscalYearWindow(fye: Date, year: number): { start: Date; end: Date } {
  const month = fye.getUTCMonth(); // 0-based
  const end = utc(year, month + 2, 0); // last day of the FYE month in `year`
  const start = utc(year - 1, month + 2, 1); // first day of the month after the prior year-end
  return { start, end };
}

const keyOf = (r: {
  filingType: string;
  periodStart?: Date | null;
  periodEnd?: Date | null;
  filingDueDate?: Date | null;
  paymentDueDate?: Date | null;
}) =>
  [r.filingType, r.periodStart?.getTime() ?? 0, r.periodEnd?.getTime() ?? 0, r.filingDueDate?.getTime() ?? 0, r.paymentDueDate?.getTime() ?? 0].join("|");

/** Build the rows a client should have for `year` for the given groups. */
export function buildReviewYearRows(client: ScheduleClientInput, year: number, groups: Set<ReviewGroup>) {
  const { start, end } = fiscalYearWindow(client.fiscalYearEnd, year);
  return buildScheduleRows(client, start, end, groups).rows;
}

export interface ReviewSyncResult {
  created: number;
  reopened: number;
  cancelled: number;
}

/**
 * Bring the client's obligations in line with the review. For each group in
 * `groups`, obligations for `year` should exist when the review says Overdue or
 * Outstanding Balance, and should not be pending otherwise.
 *
 * - Missing rows are created (marked with reviewYear), unless the client
 *   already has an equivalent row from the normal schedule.
 * - Rows previously created from the review are cancelled when the group no
 *   longer applies, and reopened when it applies again. Nothing is deleted.
 * - Rows the normal schedule created are never touched.
 */
export async function syncReviewYear(
  tenantId: string,
  actorId: string,
  client: ScheduleClientInput,
  year: number,
  groups: Set<ReviewGroup>,
  shouldExist: boolean
): Promise<ReviewSyncResult> {
  const result: ReviewSyncResult = { created: 0, reopened: 0, cancelled: 0 };

  if (shouldExist) {
    const desired = buildReviewYearRows(client, year, groups);

    const existing = await prisma.filingObligation.findMany({
      where: {
        clientId: client.id,
        OR: [
          { reviewYear: year },
          { reviewYear: null, filingDueDate: { gte: fiscalYearWindow(client.fiscalYearEnd, year).start, lte: fiscalYearWindow(client.fiscalYearEnd, year).end } },
        ],
      },
      select: {
        id: true, filingType: true, reviewYear: true, status: true,
        periodStart: true, periodEnd: true, filingDueDate: true, paymentDueDate: true,
      },
    });

    const byKey = new Map(existing.map((e) => [keyOf(e), e]));
    const toCreate: Array<Record<string, unknown>> = [];
    const toReopen: string[] = [];

    for (const d of desired) {
      const match = byKey.get(keyOf(d));
      if (!match) {
        toCreate.push({
          clientId: client.id,
          filingType: d.filingType,
          periodStart: d.periodStart ?? null,
          periodEnd: d.periodEnd ?? null,
          filingDueDate: d.filingDueDate ?? null,
          paymentDueDate: d.paymentDueDate ?? null,
          status: "Pending",
          autoGenerated: true,
          reviewYear: year,
        });
        continue;
      }
      // A review row that was cancelled (cell changed to Filed, then back)
      // becomes pending again.
      if (match.reviewYear === year && match.status === "Cancelled") toReopen.push(match.id);
    }

    if (toCreate.length > 0) {
      await prisma.filingObligation.createMany({ data: toCreate as never });
      result.created = toCreate.length;
    }
    if (toReopen.length > 0) {
      await prisma.filingObligation.updateMany({
        where: { id: { in: toReopen } },
        data: { status: "Pending" },
      });
      result.reopened = toReopen.length;
    }
  } else {
    // The review no longer asks for this year's filings: cancel the rows it
    // created, so nothing disappears and any recorded work stays visible.
    const cancelled = await prisma.filingObligation.updateMany({
      where: { clientId: client.id, reviewYear: year, status: "Pending" },
      data: { status: "Cancelled" },
    });
    result.cancelled = cancelled.count;
  }

  if (result.created || result.reopened || result.cancelled) {
    await writeAudit({
      tenantId,
      actorId,
      action: "REVIEW_SCHEDULE_SYNCED",
      entity: "Client",
      entityId: client.id,
      metadata: { year, groups: [...groups], ...result },
    });
  }
  return result;
}
